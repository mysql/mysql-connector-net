using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using MySql.EntityFrameworkCore.Basic.Tests.Utils;
using NUnit.Framework;
using System;
using System.Collections.Generic;
using System.Data.Common;
using System.Linq;
using System.Threading.Tasks;

namespace MySql.EntityFrameworkCore.Basic.Tests
{
  /// <summary>
  /// An entity whose only values are generated by the database has no column to write: MySQL
  /// inserts it with <c>INSERT INTO `t` () VALUES ()</c>.
  /// </summary>
  public class EmptyInsertTests
  {
    public class Tally
    {
      public int Id { get; set; }
    }

    public class Gauge
    {
      public int Id { get; set; }
      public int Level { get; set; }
    }

    public class CommandRecorder : DbCommandInterceptor
    {
      public List<string> Commands { get; } = new List<string>();

      public override InterceptionResult<int> NonQueryExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<int> result)
      {
        Commands.Add(command.CommandText);
        return result;
      }

      public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<DbDataReader> result)
      {
        Commands.Add(command.CommandText);
        return result;
      }
    }

    public class EmptyInsertContext : MyTestContext
    {
      public CommandRecorder Recorder { get; } = new CommandRecorder();

      protected override void OnConfiguring(DbContextOptionsBuilder optionsBuilder)
      {
        base.OnConfiguring(optionsBuilder);
        optionsBuilder.AddInterceptors(Recorder);
      }

      public DbSet<Tally> Tallies => Set<Tally>();
      public DbSet<Gauge> Gauges => Set<Gauge>();

      protected override void OnModelCreating(ModelBuilder modelBuilder)
        => modelBuilder.Entity<Gauge>().Property(g => g.Level).HasDefaultValue(5);
    }

    [OneTimeSetUp]
    public void OneTimeSetUp()
    {
      using var context = new EmptyInsertContext();
      context.Database.EnsureDeleted();
      context.Database.EnsureCreated();
    }

    [OneTimeTearDown]
    public void OneTimeTearDown()
    {
      using var context = new EmptyInsertContext();
      context.Database.EnsureDeleted();
    }

    [Test]
    public void InsertsARowWithNoColumnsToWriteAndReadsBackItsKey()
    {
      using var context = new EmptyInsertContext();
      var tally = new Tally();

      context.Add(tally);
      context.SaveChanges();

      Assert.That(tally.Id, Is.Not.EqualTo(0));
      Assert.That(context.Tallies.AsNoTracking().Any(t => t.Id == tally.Id));
    }

    [Test]
    public async Task InsertsSeveralRowsWithNoColumnsToWriteInOneSaveChanges()
    {
      using var context = new EmptyInsertContext();
      var tallies = new[] { new Tally(), new Tally(), new Tally() };

      context.AddRange(tallies);
      await context.SaveChangesAsync();

      Assert.That(tallies.Select(t => t.Id), Is.All.Not.EqualTo(0));
      Assert.That(tallies.Select(t => t.Id).Distinct().Count(), Is.EqualTo(3));
    }

    [Test]
    public void InsertsARowWhoseOnlyOtherColumnTakesItsDefaultAndReadsItBack()
    {
      using var context = new EmptyInsertContext();
      var gauge = new Gauge();

      context.Add(gauge);
      context.SaveChanges();

      Assert.That(gauge.Id, Is.Not.EqualTo(0));
      Assert.That(gauge.Level, Is.EqualTo(5));
    }

    [Test]
    public void GeneratesAnEmptyColumnAndValueList()
    {
      using var context = new EmptyInsertContext();
      context.Add(new Tally());

      context.SaveChanges();

      Assert.That(context.Recorder.Commands.Single(), Does.StartWith("INSERT INTO `Tallies` ()" + Environment.NewLine + "VALUES ();"));
    }
  }
}
